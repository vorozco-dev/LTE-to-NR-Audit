"""
Settings for the LTE to NR Audit (Ericsson).

Paths come from code/.env (ROOT_DIRECTORY=...) and can be overridden from the GUI/CLI.
Every rule threshold lives here so the reports can print exactly what was applied.
"""

import os
import sys
from dataclasses import dataclass, field, asdict
from datetime import date
from pathlib import Path

CODE_DIR = Path(__file__).resolve().parent


def _read_env():
    env = {}
    path = CODE_DIR / ".env"
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip().strip('"')
    return env


ENV = _read_env()
# code/.env first; then the environment (set to the .exe folder by build_tools/rthook_root.py in the installed app)
ROOT = Path(ENV.get("ROOT_DIRECTORY") or os.environ.get("ROOT_DIRECTORY") or CODE_DIR.parent)


def env_path(key, default):
    """Path from code/.env; relative values are taken from ROOT_DIRECTORY."""
    value = ENV.get(key)
    if not value:
        return str(default)
    p = Path(value)
    return str(p if p.is_absolute() else ROOT / p)


# code/.env keys (only ROOT_DIRECTORY is required):
#   ROOT_DIRECTORY=C:\python\lte_nr_audit_ericsson
#   INPUT_DIR=input\11172026          ENM exports (loose or in zip/rar), EPT.xlsx, propagation tables
#   EPT_XLSX=input\11172026\EPT.xlsx  ept_process.py input
#   EPT_CSV=output\ept.csv            only for ept_process.py run alone from the console
#   OUTPUT_DIR=output                 root of the work directories
#   DB=db\lte_nr_e.sqlite               database written by Process (rows per workdir), read by the audit
#   LOG_DIR=log                       GUI session logs
#   FREQ_BAND=conf\freq_band.csv      ARFCN -> band_indicator (Neighbor Relation LTE source bands)
#   ENM=tul
INPUT_DIR = env_path("INPUT_DIR", ROOT / "input" / "11172026")
EPT_XLSX = env_path("EPT_XLSX", Path(INPUT_DIR) / "EPT.xlsx")
OUTPUT_ROOT = env_path("OUTPUT_DIR", ROOT / "output")


def today():
    """Default workdir name: today's date YYYY-MM-DD."""
    return date.today().isoformat()


def default_workdir(output_root=OUTPUT_ROOT):
    """Work directory of the day: <OUTPUT_DIR>\\YYYY-MM-DD (load_report.txt and every run go there)."""
    return str(Path(output_root) / date.today().isoformat())


OUTPUT_DIR = default_workdir()
DB_PATH = env_path("DB", ROOT / "db" / "lte_nr_e.sqlite")         # written by Load Data -> Process
LOG_DIR = env_path("LOG_DIR", ROOT / "log")                     # one log file per GUI session
_FREQ_BAND_DEFAULT = ROOT / "conf" / "freq_band.csv"
if not _FREQ_BAND_DEFAULT.is_file() and hasattr(sys, "_MEIPASS"):
    # single-file .exe without conf\ next to it: the copy bundled inside the .exe
    _FREQ_BAND_DEFAULT = Path(sys._MEIPASS) / "conf" / "freq_band.csv"
FREQ_BAND = env_path("FREQ_BAND", _FREQ_BAND_DEFAULT)           # ARFCN -> band_indicator
EPT_CSV = env_path("EPT_CSV", Path(OUTPUT_DIR) / "ept.csv")     # generated by ept_process.py


def all_bands(tech, path=FREQ_BAND):
    """Every band_indicator of one technology (3g / 4g / 5g) in conf/freq_band.csv, in file order."""
    import csv
    try:
        with open(path, encoding="utf-8-sig", newline="") as f:
            rows = list(csv.DictReader(f))
    except OSError:
        return ()
    return tuple(dict.fromkeys(r["band_indicator"].strip() for r in rows
                               if r["tech"].strip().lower() == tech and r["band_indicator"].strip()))


# Bands offered in the GUI (fixed): the band_indicator values active in the EPT (inventory sheets,
# not PLAN) on 2026-11-18, named as in conf/freq_band.csv. "All" = every band of the list.
LTE_BANDS = ("band_2_pcs", "band_4_aws", "band_5_850", "band_7_2600", "band_26_800")
NR_BANDS = ("band_7_2600",)


@dataclass
class Settings:
    # --- inputs -----------------------------------------------------------------
    db: str = DB_PATH                                        # ENM tables, EPT, propagation (Process)
    workdir: str = field(default_factory=today)              # rows of the database audited
    enm: str = ENV.get("ENM", "tul")                         # ENM name used in the file names
    output_dir: str = OUTPUT_DIR

    # --- what to run ------------------------------------------------------------
    part1: bool = True                                       # Audit X2 TermPoint LTE to 5G
    part2: bool = True                                       # Audit Neighbor Relation LTE to 5G
    scope: str = "all"                                       # all | nodes (GUI: All | Node list)
    scope_names: str = ""                                    # node names, comma/semicolon/newline separated

    # --- Audit rules ----------------------------------------------------------------
    source_bands: tuple = LTE_BANDS                          # LTE cells audited, by band_indicator of
                                                             # conf/freq_band.csv (from earfcndl); default all
    target_bands: tuple = NR_BANDS                           # NR cells that qualify a site / are targets,
                                                             # by band_indicator (from ssbFrequency); default all
    active_only_for_add: bool = True                         # ADD needs UNLOCKED+ENABLED source and target
    max_add_all_tier: int = 1                                # ADD every missing NR cell (overlap or not) for tier 0..1
    max_add_tier: int = 4                                    # ADD missing NR cells with fan overlap for tier 0..4
    min_delete_tier: int = 6                                 # DELETE when tier >= 6 (i.e. > 5)
    zero_overlap_min_tier: int = 2                           # zero overlap only deletes from this tier up
                                                             # (tier 0 same site and tier 1 first ring kept)
    max_site_km: float = 30.0                                # applied after the tier rules: no ADD towards a
                                                             # site farther than this (km between sites, EPT),
                                                             # an existing relation to it is DELETE, and the
                                                             # Graphical Audit map leaves it out of the tiers
    default_beam: float = 65.0                               # used (and flagged) when the EPT has no beam
    arc_step_deg: float = 2.0                                # fan arc resolution

    # --- X2 TermPoint rules -------------------------------------------------------
    x2_router_preference: tuple = ("NR",)                    # router whose X2 address is proposed

    def rule_problems(self):
        """Contradictory Audit Rules (an ADD tier reaching a DELETE tier), as messages."""
        out = []
        if self.max_add_all_tier >= self.zero_overlap_min_tier:
            out.append(f"'ADD ... within tier' ({self.max_add_all_tier}) must be lower than 'DELETE ... with no "
                       f"fan overlap from tier' ({self.zero_overlap_min_tier})")
        if self.max_add_tier >= self.min_delete_tier:
            out.append(f"'ADD ... with fan overlap within tier' ({self.max_add_tier}) must be lower than "
                       f"'DELETE ... from tier' ({self.min_delete_tier})")
        if not self.max_site_km > 0:
            out.append(f"'Max Site distance (Km)' ({self.max_site_km:g}) must be greater than 0")
        return out

    def scope_set(self):
        import re
        return {s.strip().upper() for s in re.split(r"[,;\n]+", self.scope_names) if s.strip()}

    def as_rows(self):
        return [{"Setting": k, "Value": ", ".join(v) if isinstance(v, tuple) else v}
                for k, v in asdict(self).items()]
